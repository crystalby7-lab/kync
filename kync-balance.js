  // 오늘 쓸 질문 10개 선택 (날짜 기반 일관성)
  _getTodaysQuestions() {
    const dayNum = localDayNum();
    const shuffled = [...this.QUESTIONS].sort((a,b) => {
      const ha = (a.id * 7 + dayNum * 13) % 100;
      const hb = (b.id * 7 + dayNum * 13) % 100;
      return ha - hb;
    });
    return shuffled.slice(0, this.MAX_PER_DAY);
  },
